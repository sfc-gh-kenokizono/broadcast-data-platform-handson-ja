  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION BCAST_PLATFORM_GIT_API TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;

-- ============================================
-- 4. 空のRAWテーブルと内部ステージ
-- ============================================
-- ここからはENGINEERの権限で作成し、新しい表などをこのロールの所有物にします。
-- SECONDARY ROLES NONEは他の有効ロールの権限に頼らず作業する指定です。管理者権限で不足を見落とすのを防ぎます。
-- 以下のUSEは現在のセッションだけの選択です。ユーザーの既定ロール・既定WHを変更する設定ではありません。
USE ROLE BCAST_PLATFORM_ENGINEER_ROLE;
USE SECONDARY ROLES NONE;
USE DATABASE BCAST_PLATFORM_HANDSON;
USE SCHEMA BCAST_PLATFORM_HANDSON.RAW;
USE WAREHOUSE BCAST_PLATFORM_COMMON_WH;

-- 視聴ログの1行は、ある端末の視聴開始から終了までの区間です。局・端末・時間・開始時のジャンルを保持します。
-- このCREATEは列名と型を決めるだけです。初回は空の表ができ、01_02_load_parquet.sqlで初めて行が入ります。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01 (
  EVENT_ID VARCHAR,
  NETWORK_ID VARCHAR,
  DEVICE_ID VARCHAR,
  VIEW_FROM TIMESTAMP_NTZ,
  VIEW_TO TIMESTAMP_NTZ,
  GENRE VARCHAR
);
-- LIKEはNW01と同じ列・型の空の表を作ります。NW01にデータがあっても、その行を他局へコピーしません。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW02
  LIKE BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01;
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW03
  LIKE BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01;
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW04
  LIKE BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01;
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW05
  LIKE BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01;
-- LABEL_AVAILABLEは正解ラベルを使えるかを示す真偽値です。TRUEの端末だけTARGET_F1に0または1を持ちます。
-- TARGET_F1=1は合成世帯にF1層（20〜34歳女性）がいる端末、0はいないと分かっている端末です。単身世帯も含みます。
-- FALSEの端末は正解が不明なのでTARGET_F1=NULL。NULLを0にすると「不明」を「いない」と誤って学習させます。
-- このラベルは世帯にF1層がいるかどうかであり、実際に画面を見た人の性年代やF1の視聴人数を示すものではありません。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.DEVICE_LABELS (
  DEVICE_ID VARCHAR,
  LABEL_AVAILABLE BOOLEAN,
  TARGET_F1 INTEGER
);
-- PROGRAM_MASTERは番組の説明、PROGRAM_SCHEDULEはその番組をいつ放送したかを保持します。
-- 同じ番組でも放送日・時間が異なるため、番組そのものの情報と放送回の情報を別の表にします。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.PROGRAM_MASTER (
  PROGRAM_ID VARCHAR(8),
  PROGRAM_NAME VARCHAR(60),
  NETWORK_ID VARCHAR(4),
  GENRE VARCHAR(20),
  TIME_SLOT VARCHAR(20),
  DURATION_MIN NUMBER(4,0),
  SYNOPSIS VARCHAR(400)
);
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.PROGRAM_SCHEDULE (
  PROGRAM_ID VARCHAR(8),
  NETWORK_ID VARCHAR(4),
  AIR_DATE DATE,
  AIR_FROM TIMESTAMP_NTZ,
  AIR_TO TIMESTAMP_NTZ
);

-- 以下2表は学習用データではなく、01_02_load_parquet.sqlが再実行の安全性を自動確認するための管理表です。参加者は直接編集しません。
-- DATASET_RELEASE_FILESは取込済みの版・行数・内容の照合値を記録し、同じデータを再利用できるかの比較に使います。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.DATASET_RELEASE_FILES (
  DATASET_VERSION VARCHAR NOT NULL,
  TABLE_NAME VARCHAR NOT NULL,
  FILE_NAME VARCHAR NOT NULL,
  FILE_CONTENT_KEY VARCHAR NOT NULL,
  ROW_COUNT NUMBER(38,0) NOT NULL,
  ROW_FINGERPRINT NUMBER(38,0) NOT NULL,
  LOADED_AT TIMESTAMP_NTZ NOT NULL
);
-- DATASET_LOAD_LOCKは取込処理が管理用の1行を更新し、別の取込と同時にRAWを書き換えないようにするための表です。
-- MERGEはLOCK_ID=1の行がなければ追加します。行の削除や追加でエラーを回避せず、セットアップも同時実行しません。
CREATE TABLE IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW.DATASET_LOAD_LOCK (
  LOCK_ID INTEGER NOT NULL,
  LAST_LOADER VARCHAR
);
MERGE INTO BCAST_PLATFORM_HANDSON.RAW.DATASET_LOAD_LOCK AS target
USING (SELECT 1 AS LOCK_ID) AS source ON target.LOCK_ID = source.LOCK_ID
WHEN NOT MATCHED THEN INSERT (LOCK_ID) VALUES (source.LOCK_ID);

-- FILE FORMATはParquetを「どう読むか」の設定です。COMPRESSION=AUTOはZSTD圧縮済みの教材を判別して読みます。
-- ファイルを別の圧縮方式へ再圧縮する指定ではありません。LOGICAL_TYPE等は日時やバイナリの型の解釈に関わります。
CREATE FILE FORMAT IF NOT EXISTS BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET
  TYPE = PARQUET
  COMPRESSION = AUTO
  USE_LOGICAL_TYPE = TRUE
  USE_VECTORIZED_SCANNER = TRUE
  BINARY_AS_TEXT = FALSE;
-- STAGEはファイルの置き場、RAWのTABLEは読み取った行の格納先です。WHはその読取・書込を計算します。
-- 作成成功時点では置き場と読取設定ができただけです。01_02_load_parquet.sqlでファイルを置いてから表へ読み込みます。
CREATE STAGE IF NOT EXISTS BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE
  FILE_FORMAT = (FORMAT_NAME = 'BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET');

-- ============================================
-- 5. 公開リポジトリに接続し、使用するデータを確認します。
-- FETCHは必須です。Snowflake側のリポジトリ情報を取得してからLISTを実行してください。
-- GitHubのリポジトリは用意済みです。下のCREATEは、Snowflake側に取込用の参照先を作ります。
-- branches/main/data/は、取得したmainブランチのdataフォルダを指します。LISTは一覧表示だけで、取込は行いません。
-- Parquetが8個（局別ログ5、番組マスタ1、放送予定1、ラベル1）あることを確認します。
-- FETCH・LIST・ファイル読取でエラーが出たら、表示内容を確認して講師に連絡してください。
-- 8ファイルを確認できたら、第1章に沿ってGit Workspaceを作り、その中で01_02_load_parquet.sqlを開きます。
-- ============================================
-- このGIT REPOSITORYはSQLが参照するSnowflake内のGitコピーです。SQL等を開いて編集するGit Workspaceとは別です。
-- FETCHはそのコピーを更新します。01_02_load_parquet.sqlの取込元はbranches/main/data/なので、Workspace内の未反映の編集は読みません。
CREATE GIT REPOSITORY IF NOT EXISTS BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_REPO
  API_INTEGRATION = BCAST_PLATFORM_GIT_API
  ORIGIN = 'https://github.com/sfc-gh-kenokizono/broadcast-data-platform-handson-ja.git';
ALTER GIT REPOSITORY BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_REPO FETCH;
LIST @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_REPO/branches/main/data/;