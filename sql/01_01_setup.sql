-- ============================================
-- 目的: 教材専用のロール、データベース、計算用ウェアハウス、データ取込先を準備します。
-- 前提: 講師が指定したハンズオン用アカウントで、ACCOUNTADMINを使用できること。
-- 実行方法: 接続先を確認し、上から順に実行してください。エラーが出たら後続へ進まないでください。
-- 同名オブジェクトが別用途で存在する場合は実行しないでください。
-- 完了の目安: 最後のLISTでmainブランチのdataフォルダにあるParquetファイル8個を確認できること。
-- 1. 管理者による専用環境の準備
-- ============================================
-- USE ROLEは、このセッションで「どの権限を使って作業するか」を切り替えます。権限を配るGRANTとは別です。
-- ここではロールや接続設定を準備するためにACCOUNTADMINを使い、準備後は教材専用ロールへ切り替えます。
USE ROLE ACCOUNTADMIN;

-- ロールは権限をまとめる入れ物です。ENGINEERは作成・加工、ANALYSTは集計結果の参照に使います。
-- IF NOT EXISTSは同名ロールがあれば作り直しません。既存の権限を初期化する指定ではありません。
CREATE ROLE IF NOT EXISTS BCAST_PLATFORM_ENGINEER_ROLE;
CREATE ROLE IF NOT EXISTS BCAST_PLATFORM_ANALYST_ROLE;
-- TO ROLE SYSADMINで、SYSADMINが教材ロールの権限を継承する階層を作ります。
-- これは管理用の親子関係であり、現在のユーザーへ教材ロールを直接割り当てる操作ではありません。
GRANT ROLE BCAST_PLATFORM_ENGINEER_ROLE TO ROLE SYSADMIN;
GRANT ROLE BCAST_PLATFORM_ANALYST_ROLE TO ROLE SYSADMIN;

-- CURRENT_USER()は実行中の参加者のユーザー名です。SETで保存し、IDENTIFIERでGRANT先の識別子として使います。
-- TO USERによって本人に2つのロールを直接割り当て、後でUSE ROLEで選べるようにします。
SET current_user_name = (SELECT CURRENT_USER());
GRANT ROLE BCAST_PLATFORM_ENGINEER_ROLE TO USER IDENTIFIER($current_user_name);
GRANT ROLE BCAST_PLATFORM_ANALYST_ROLE TO USER IDENTIFIER($current_user_name);

-- DATABASEは表などを整理する最上位の入れ物、SCHEMAはその中の区画、TABLEはデータを格納する表です。
-- WAREHOUSEはSQLを処理する計算資源（CPU・メモリ等）です。データの永続保存先ではありません。
CREATE DATABASE IF NOT EXISTS BCAST_PLATFORM_HANDSON;
-- XSMALLは計算資源のサイズ。AUTO_SUSPEND=60は非稼働60秒後の停止、AUTO_RESUMEは処理が必要なときの再開です。
-- INITIALLY_SUSPENDEDは作成直後を停止状態にします。停止しても表のデータは消えず、保存料金は別に発生します。
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_COMMON_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
-- USE WAREHOUSEは以後のSQLで使う計算資源の選択です。DBの選択やデータの移動ではありません。
USE WAREHOUSE BCAST_PLATFORM_COMMON_WH;

-- RAWは受け取ったデータ、NW01〜NW05は局別の加工結果、COMMONは5局の共通集計を置く区画です。
-- MLは学習・予測、MARTは分析向けの定義やアプリ、INTEGRATIONSはGit参照先や取込ファイルの置き場に使います。
-- ここでは区画だけを作るので、成功しても視聴データの表や行はまだ増えません。次に計算資源と権限をそろえます。
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.RAW;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.NW01;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.NW02;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.NW03;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.NW04;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.NW05;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.COMMON;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.ML;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.MART;
CREATE SCHEMA IF NOT EXISTS BCAST_PLATFORM_HANDSON.INTEGRATIONS;

-- 局別処理をそれぞれのWHで動かすと、他局や共通処理と計算資源を分けられます。保存先のスキーマとは別の指定です。
-- 最後のCOMMON_WHは上で作成済みならそのまま残ります。IF NOT EXISTSでは既存WHのサイズや停止設定は変更しません。
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_NW01_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_NW02_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_NW03_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_NW04_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_NW05_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS BCAST_PLATFORM_COMMON_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- ============================================
-- 2. エンジニアの作成権限とアナリストの参照権限
-- 後続の表などは作成したロールが所有します。利用者の既定ロール・既定ウェアハウスは変更しません。
-- ============================================
-- DATABASEのUSAGEは、そのDB内のオブジェクトを使うための入口です。これだけで表の中身を読めるわけではありません。
-- 表の参照にはDBとSCHEMAのUSAGEに加え、その表のSELECTが必要です。処理に使うWHのUSAGEも別途付けます。
GRANT USAGE ON DATABASE BCAST_PLATFORM_HANDSON TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON DATABASE BCAST_PLATFORM_HANDSON TO ROLE BCAST_PLATFORM_ANALYST_ROLE;

-- スキーマごとのCREATE権限は「その区画で何を作れるか」です。RAWでは表、NW/COMMONではdbtの加工物を作ります。
-- MLではモデルやNotebook、MARTでは分析ビューやAgentを作るため、区画の用途に合わせて権限を分けています。
GRANT USAGE, CREATE TABLE ON SCHEMA BCAST_PLATFORM_HANDSON.RAW TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.NW01 TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.NW02 TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.NW03 TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.NW04 TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.NW05 TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT, CREATE DBT PROJECT
  ON SCHEMA BCAST_PLATFORM_HANDSON.COMMON TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE MODEL, CREATE NOTEBOOK, CREATE STAGE
  ON SCHEMA BCAST_PLATFORM_HANDSON.ML TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE SEMANTIC VIEW, CREATE AGENT, CREATE STREAMLIT, CREATE STAGE
  ON SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE, CREATE GIT REPOSITORY, CREATE STAGE, CREATE FILE FORMAT
  ON SCHEMA BCAST_PLATFORM_HANDSON.INTEGRATIONS TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;

-- ENGINEERには全局と共通のWH、ANALYSTには分析で使う共通WHの利用を許可します。
-- WHのUSAGEは計算資源を使う権限であり、RAWやMLのデータを読む権限にはなりません。
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_NW01_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_NW02_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_NW03_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_NW04_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_NW05_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_COMMON_WH TO ROLE BCAST_PLATFORM_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE BCAST_PLATFORM_COMMON_WH TO ROLE BCAST_PLATFORM_ANALYST_ROLE;

-- ANALYSTの参照先はCOMMONとMARTです。ALLは今ある表・ビュー、FUTUREはこの後に作られる表・ビューが対象です。
-- 片方だけでは既存分か新規分が漏れるため、両方を付けます。スキーマのUSAGEだけではSELECTの代わりになりません。
GRANT USAGE ON SCHEMA BCAST_PLATFORM_HANDSON.COMMON TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT USAGE ON SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA BCAST_PLATFORM_HANDSON.COMMON TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA BCAST_PLATFORM_HANDSON.COMMON TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ANALYST_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA BCAST_PLATFORM_HANDSON.MART TO ROLE BCAST_PLATFORM_ANALYST_ROLE;

