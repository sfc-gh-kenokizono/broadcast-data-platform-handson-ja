-- 実測件数。生成後の検証サマリーと照合し、旧サンプルの固定値を使わない。
SELECT 'NW01' AS SOURCE, COUNT(*) AS ROW_COUNT FROM BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW01
UNION ALL SELECT 'NW02', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW02
UNION ALL SELECT 'NW03', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW03
UNION ALL SELECT 'NW04', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW04
UNION ALL SELECT 'NW05', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW05
UNION ALL SELECT 'DEVICE_LABELS', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.DEVICE_LABELS
UNION ALL SELECT 'PROGRAM_MASTER', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.PROGRAM_MASTER
UNION ALL SELECT 'PROGRAM_SCHEDULE', COUNT(*) FROM BCAST_PLATFORM_HANDSON.RAW.PROGRAM_SCHEDULE
ORDER BY SOURCE;

-- 合成TV世帯のF1在籍ラベル。視聴中の個人属性ではない。クラス別件数は実測する。
SELECT COUNT(DISTINCT DEVICE_ID) AS DEVICES,
       COUNT(*) - COUNT(DISTINCT DEVICE_ID) AS DUPLICATE_DEVICE_ROWS,
       COUNT_IF(LABEL_AVAILABLE) AS KNOWN_LABELS,
       COUNT_IF(NOT LABEL_AVAILABLE AND TARGET_F1 IS NULL) AS UNKNOWN_LABELS,
       COUNT_IF(LABEL_AVAILABLE AND TARGET_F1 = 0) AS CLASS_ZERO,
       COUNT_IF(LABEL_AVAILABLE AND TARGET_F1 = 1) AS CLASS_ONE,
       COUNT_IF(NOT LABEL_AVAILABLE AND TARGET_F1 IS NOT NULL) AS LEAKED_TARGETS,
       COUNT(DISTINCT DEVICE_ID) - 20000 AS COHORT_DIFFERENCE,
       COUNT_IF(LABEL_AVAILABLE) - 2000 AS PANEL_DIFFERENCE,
       COUNT_IF(NOT LABEL_AVAILABLE AND TARGET_F1 IS NULL) - 18000 AS UNLABELED_DIFFERENCE
FROM BCAST_PLATFORM_HANDSON.RAW.DEVICE_LABELS;