-- 2026年5〜7月の合成時刻。元ログ行の無損失変換ではない。
SELECT $1:DEVICE_ID::VARCHAR AS DEVICE_ID,
       $1:VIEW_FROM::TIMESTAMP_NTZ AS VIEW_FROM,
       $1:VIEW_TO::TIMESTAMP_NTZ AS VIEW_TO
FROM @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE/viewing_log_nw01.parquet
  (FILE_FORMAT => 'BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET')
