DECLARE
  incompatible_schema EXCEPTION (-20001, 'RAW schema mismatch: expected six viewing columns, original program master/schedule schemas and DEVICE_ID/LABEL_AVAILABLE/TARGET_F1. Stop; do not load the old small sample.');
  incompatible_data EXCEPTION (-20002, 'Existing viewing rows are outside the unified C000001-C020000 May-July 2026 cohort. Stop and review migration separately; no viewing tables are reset here.');
  incompatible_files EXCEPTION (-20003, 'Expected all eight Parquet files and nonempty F1 label data with the new three-column schema. Check main/data and stage before retrying.');
  schema_mismatches INTEGER;
  legacy_rows INTEGER;
  staged_files INTEGER;
  label_rows INTEGER;
  invalid_labels INTEGER;
  panel_rows INTEGER;
  unique_devices INTEGER;
  viewing_table VARCHAR;
BEGIN
  WITH expected AS (
    SELECT 'VIEWING_LOG_' || station.COLUMN1 AS TABLE_NAME,
           definition.COLUMN1 AS COLUMN_NAME, definition.COLUMN2 AS DATA_TYPE
    FROM (VALUES ('NW01'), ('NW02'), ('NW03'), ('NW04'), ('NW05')) AS station
    CROSS JOIN (VALUES ('EVENT_ID', 'TEXT'), ('NETWORK_ID', 'TEXT'), ('DEVICE_ID', 'TEXT'),
                       ('VIEW_FROM', 'TIMESTAMP_NTZ'), ('VIEW_TO', 'TIMESTAMP_NTZ'), ('GENRE', 'TEXT')) AS definition
    UNION ALL
    SELECT COLUMN1, COLUMN2, COLUMN3 FROM VALUES
      ('DEVICE_LABELS', 'DEVICE_ID', 'TEXT'), ('DEVICE_LABELS', 'LABEL_AVAILABLE', 'BOOLEAN'),
      ('DEVICE_LABELS', 'TARGET_F1', 'NUMBER'),
      ('PROGRAM_MASTER', 'PROGRAM_ID', 'TEXT'), ('PROGRAM_MASTER', 'PROGRAM_NAME', 'TEXT'),
      ('PROGRAM_MASTER', 'NETWORK_ID', 'TEXT'), ('PROGRAM_MASTER', 'GENRE', 'TEXT'),
      ('PROGRAM_MASTER', 'TIME_SLOT', 'TEXT'), ('PROGRAM_MASTER', 'DURATION_MIN', 'NUMBER'),
      ('PROGRAM_MASTER', 'SYNOPSIS', 'TEXT'),
      ('PROGRAM_SCHEDULE', 'PROGRAM_ID', 'TEXT'), ('PROGRAM_SCHEDULE', 'NETWORK_ID', 'TEXT'),
      ('PROGRAM_SCHEDULE', 'AIR_DATE', 'DATE'), ('PROGRAM_SCHEDULE', 'AIR_FROM', 'TIMESTAMP_NTZ'),
      ('PROGRAM_SCHEDULE', 'AIR_TO', 'TIMESTAMP_NTZ')
  ), actual AS (
    SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NUMERIC_SCALE
    FROM BCAST_PLATFORM_HANDSON.INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'RAW' AND TABLE_NAME IN
      ('VIEWING_LOG_NW01', 'VIEWING_LOG_NW02', 'VIEWING_LOG_NW03', 'VIEWING_LOG_NW04',
       'VIEWING_LOG_NW05', 'DEVICE_LABELS', 'PROGRAM_MASTER', 'PROGRAM_SCHEDULE')
  )
  SELECT COUNT(*) INTO :schema_mismatches
  FROM expected FULL OUTER JOIN actual
    ON expected.TABLE_NAME = actual.TABLE_NAME AND expected.COLUMN_NAME = actual.COLUMN_NAME
  WHERE expected.COLUMN_NAME IS NULL OR actual.COLUMN_NAME IS NULL
     OR expected.DATA_TYPE != actual.DATA_TYPE
     OR (actual.DATA_TYPE = 'NUMBER' AND actual.NUMERIC_SCALE != 0);
  IF (schema_mismatches > 0) THEN
    RAISE incompatible_schema;
  END IF;
  SELECT COUNT(*) INTO :legacy_rows FROM BCAST_PLATFORM_HANDSON.RAW.DEVICE_LABELS
  WHERE DEVICE_ID IS NULL OR NOT REGEXP_LIKE(DEVICE_ID, 'C[0-9]{6}')
     OR TRY_TO_NUMBER(SUBSTR(DEVICE_ID, 2)) NOT BETWEEN 1 AND 20000
     OR LABEL_AVAILABLE IS NULL
     OR (LABEL_AVAILABLE AND (TARGET_F1 IS NULL OR TARGET_F1 NOT IN (0, 1)))
     OR (NOT LABEL_AVAILABLE AND TARGET_F1 IS NOT NULL);
  IF (legacy_rows > 0) THEN
    RAISE incompatible_data;
  END IF;
  FOR station IN 1 TO 5 DO
    viewing_table := 'BCAST_PLATFORM_HANDSON.RAW.VIEWING_LOG_NW0' || station;
    SELECT COUNT(*) INTO :legacy_rows FROM IDENTIFIER(:viewing_table)
    WHERE DEVICE_ID IS NULL OR NOT REGEXP_LIKE(DEVICE_ID, 'C[0-9]{6}')
       OR TRY_TO_NUMBER(SUBSTR(DEVICE_ID, 2)) NOT BETWEEN 1 AND 20000
       OR (VIEW_FROM IS NOT NULL AND (VIEW_FROM < '2026-05-01'::TIMESTAMP_NTZ
                                     OR VIEW_FROM >= '2026-08-01'::TIMESTAMP_NTZ));
    IF (legacy_rows > 0) THEN
      RAISE incompatible_data;
    END IF;
  END FOR;

ALTER GIT REPOSITORY BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_REPO FETCH;
COPY FILES INTO @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE
  FROM @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_REPO/branches/main/data/
  FILES = ('viewing_log_nw01.parquet', 'viewing_log_nw02.parquet',
           'viewing_log_nw03.parquet', 'viewing_log_nw04.parquet',
           'viewing_log_nw05.parquet', 'program_master.parquet',
           'program_schedule.parquet', 'device_labels.parquet')
  DETAILED_OUTPUT = TRUE;

-- COPY FILESは存在しない指定ファイルをスキップする。
SELECT COUNT(*) INTO :staged_files FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
IF (staged_files != 8) THEN
  RAISE incompatible_files;
END IF;
SELECT IFF(COUNT(*) = 3 AND COUNT_IF(COLUMN_NAME IN ('DEVICE_ID', 'LABEL_AVAILABLE', 'TARGET_F1')) = 3, 0, 1)
INTO :schema_mismatches
FROM TABLE(INFER_SCHEMA(
  LOCATION => '@BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE/device_labels.parquet',
  FILE_FORMAT => 'BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET'
));
IF (schema_mismatches > 0) THEN
  RAISE incompatible_files;
END IF;
SELECT COUNT(*), COUNT_IF(
    COALESCE(ARRAY_CONTAINS('TARGET_SPORTS_FAN'::VARIANT, OBJECT_KEYS($1)), FALSE)
    OR NOT COALESCE(REGEXP_LIKE($1:DEVICE_ID::VARCHAR, 'C[0-9]{6}'), FALSE)
    OR TRY_TO_NUMBER(SUBSTR($1:DEVICE_ID::VARCHAR, 2)) NOT BETWEEN 1 AND 20000
    OR COALESCE(TYPEOF($1:LABEL_AVAILABLE) != 'BOOLEAN', TRUE)
    OR ($1:LABEL_AVAILABLE::BOOLEAN AND ($1:TARGET_F1::INTEGER IS NULL OR $1:TARGET_F1::INTEGER NOT IN (0, 1)))
    OR (NOT $1:LABEL_AVAILABLE::BOOLEAN AND $1:TARGET_F1::INTEGER IS NOT NULL)
) INTO :label_rows, :invalid_labels
FROM @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE/device_labels.parquet
  (FILE_FORMAT => 'BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET');
IF (label_rows = 0 OR invalid_labels > 0) THEN
  RAISE incompatible_files;
END IF;
SELECT COUNT(DISTINCT $1:DEVICE_ID::VARCHAR), COUNT_IF($1:LABEL_AVAILABLE::BOOLEAN)
INTO :unique_devices, :panel_rows
FROM @BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_RAW_STAGE/device_labels.parquet
  (FILE_FORMAT => 'BCAST_PLATFORM_HANDSON.INTEGRATIONS.BCAST_PLATFORM_PARQUET');
IF (label_rows != 20000 OR unique_devices != 20000 OR panel_rows != 2000) THEN
  RAISE incompatible_files;
END IF;

